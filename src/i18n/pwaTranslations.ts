export const PWA_DISMISS_STORAGE_KEY = 'sarson_subah_pwa_dismissed_at';
export const SEVEN_DAYS_MS = 7 * 24 * 60 * 60 * 1000;

export function getPwaTranslations(langCode: string): PwaTranslationStrings {
  const normalized = (langCode || 'en').trim().toLowerCase();
  return PWA_TRANSLATIONS[normalized] || PWA_TRANSLATIONS.en;
}

export function isPwaDismissedRecently(nowMs: number = Date.now()): boolean {
  if (typeof window === 'undefined') return false;
  try {
    const raw = window.localStorage.getItem(PWA_DISMISS_STORAGE_KEY);
    if (!raw) return false;
    const timestamp = Number(raw);
    if (!Number.isFinite(timestamp) || timestamp <= 0) return false;
    return nowMs - timestamp < SEVEN_DAYS_MS;
  } catch {
    return false;
  }
}

export function persistPwaDismissal(nowMs: number = Date.now()): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(PWA_DISMISS_STORAGE_KEY, String(nowMs));
  } catch {
    // Ignore storage error
  }
}

export function clearPwaDismissal(): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.removeItem(PWA_DISMISS_STORAGE_KEY);
  } catch {
    // Ignore storage error
  }
}

export function detectIsStandalone(): boolean {
  if (typeof window === 'undefined') return false;
  try {
    const mqStandalone =
      typeof window.matchMedia === 'function' &&
      window.matchMedia('(display-mode: standalone)').matches;
    const navStandalone =
      (window.navigator as unknown as { standalone?: boolean }).standalone === true;
    return Boolean(mqStandalone || navStandalone);
  } catch {
    return false;
  }
}

export function detectIsIOS(): boolean {
  if (typeof window === 'undefined') return false;
  try {
    const ua = window.navigator.userAgent || '';
    const isAppleMobile = /iphone|ipad|ipod/i.test(ua);
    const isIpadOS =
      window.navigator.platform === 'MacIntel' && window.navigator.maxTouchPoints > 1;
    return isAppleMobile || isIpadOS;
  } catch {
    return false;
  }
}
