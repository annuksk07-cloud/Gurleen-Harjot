export interface ResolvedPersonalNote {
  relative: Relative | null;
  isRelative: boolean;
  displayName: string;
  chip: string;
  greeting: string;
  message: string;
  signOff: string;
}

export function resolvePersonalNote(
  rawName: string | null | undefined,
  langCode: string = 'en',
  config?: Partial<WeddingConfig>
): ResolvedPersonalNote {
  const trimmed = (rawName || '').trim();
  const relative = trimmed ? matchRelative(trimmed) : null;
  const lang = resolveNoteLang(langCode);

  const resolvedGuestName = getGuestDisplayName(trimmed, lang);
  const displayName = resolvedGuestName || DEFAULT_GUEST_BY_LANG[lang];

  const chip = relative ? relative.chips[lang] : GENERIC_CHIP_BY_LANG[lang];
  const greeting = formatGreetingByLang(displayName, lang);

  const generic = getGenericMessage(trimmed || 'guest');
  const message = relative ? relative.messages[lang] : generic.messages[lang];

  const coupleNames = getSafeCoupleSignOffNames(config, lang);
  const signOff = formatSignOffByLang(coupleNames, lang);

  return {
    relative,
    isRelative: Boolean(relative),
    displayName,
    chip,
    greeting,
    message,
    signOff,
  };
}
